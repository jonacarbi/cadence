import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const dir=mkdtempSync(join(tmpdir(),'cadence-agent-'));process.env.CADENCE_DIR=join(dir,'app');
const {db,insert,encrypt,all,one,update}=await import('../src/db.js');
const {importDesignSystem,activateDesignSystem}=await import('../src/design-systems.js');
const {createAgentRequest,runAgent,requestById,continueRequest,scheduleRequest}=await import('../src/content-agent.js');
const {editPost}=await import('../src/workflow.js');
const {createApiServer,listen}=await import('../src/api.js');
const {ownerToken,agentToken}=await import('../src/auth.js');
const source=join(dir,'source');mkdirSync(source);writeFileSync(join(source,'DESIGN.md'),'# Distinct brand\nPlum, editorial typography.');
const brand=insert('brands',{slug:'test',name:'Test',url:'https://example.com',dir:source});
activateDesignSystem(brand,importDesignSystem(brand,{source_path:source}).id);
for(const platform of ['mastodon','bluesky'])insert('accounts',{brand_id:brand,platform,label:platform,auth_enc:encrypt({})});
insert('accounts',{brand_id:brand,platform:'x',label:'Paused',auth_enc:encrypt({}),paused:1});
const server=createApiServer(),address=await listen(server,0),base=`http://127.0.0.1:${address.port}`;
test.after(async()=>{await new Promise(r=>server.close(r));db.close();rmSync(dir,{recursive:true,force:true});});
const versions=r=>Object.fromEntries(r.posts.map(p=>[p.id,p.version]));
const generateFor=request=>async prompt=>{
 assert.match(prompt,/Distinct brand/);
 assert.match(prompt,/mastodon/);assert.match(prompt,/bluesky/);
 return {posts:request.input.dates.filter(d=>prompt.match(/Use these exact days: ([\d, ]+)/)?.[1].split(',').map(Number).includes(d.day)).map(({day})=>({day,topic:`Topic ${day}`,copy:{mastodon:'A useful, specific caption.',bluesky:'A shorter, distinct caption.'},image_prompt:'Plum editorial scene',format:'text'}))};
};
test('single prompt fans out to all active brand platforms and keeps the exact timestamp',async()=>{
 const at=new Date(Date.now()+86400000).toISOString();
 const r=createAgentRequest({brand_id:brand,prompt:'Launch our coffee subscription',scheduled_at:at});
 await runAgent(r.id,()=>{},{generate:generateFor(r),produce:async()=>{}});
 const result=requestById(r.id);assert.equal(result.status,'review');assert.equal(result.posts.length,1);
 assert.deepEqual(result.posts[0].platforms,['mastodon','bluesky']);assert.equal(result.posts[0].scheduled_at,at);
 assert.equal(result.posts[0].status,'draft');assert.equal(result.posts[0].approved_by,null);
});
test('month creates every date, resumes without duplicated drafts, and schedules atomically',async()=>{
 const r=createAgentRequest({brand_id:brand,prompt:'Create a whole month of content',month:'2096-02',time_zone:'Pacific/Kiritimati',hour:10});
 assert.equal(r.input.dates.length,29);
 await assert.rejects(runAgent(r.id,()=>{},{generate:generateFor(r),produce:async()=>{throw new Error('Image provider unavailable');}}),/unavailable/);
 assert.equal(requestById(r.id).posts.length,29);
 await runAgent(r.id,()=>{},{generate:async()=>{throw new Error('Must not regenerate');},produce:async()=>{}});
 let result=requestById(r.id);assert.equal(result.posts.length,29);
 assert.equal(result.posts[0].scheduled_at,'2096-01-31T20:00:00.000Z');
 const account=one("SELECT id FROM accounts WHERE brand_id=? AND platform='bluesky'",brand);
 update('accounts',account.id,{paused:1});
 assert.throws(()=>scheduleRequest(r.id,versions(result),'owner'),/Every platform/);
 assert.ok(requestById(r.id).posts.every(p=>p.status==='draft'));
 assert.equal(all('SELECT * FROM deliveries').length,0);
 update('accounts',account.id,{paused:0});
 result=scheduleRequest(r.id,versions(result),'owner');
 assert.equal(result.status,'scheduled');assert.ok(result.posts.every(p=>p.status==='scheduled'));
 assert.equal(all('SELECT * FROM deliveries').length,58);
 assert.throws(()=>scheduleRequest(r.id,versions(result),'owner'),/review/);
});
test('stale batch approval never approves edited drafts',async()=>{
 const r=createAgentRequest({brand_id:brand,prompt:'One post'});
 await runAgent(r.id,()=>{},{generate:generateFor(r),produce:async()=>{}});
 const result=requestById(r.id);editPost(result.posts[0].id,{topic:'Changed'},1);
 assert.throws(()=>scheduleRequest(r.id,versions(result),'owner'),/changed/);
 assert.equal(requestById(r.id).posts[0].status,'draft');
});
test('month planning checkpoints successful batches and resumes without paying to repeat them',async()=>{
 const r=createAgentRequest({brand_id:brand,prompt:'A month of content',month:'2096-03'});
 let calls=0;
 await assert.rejects(runAgent(r.id,()=>{},{generate:async prompt=>{if(++calls===2)throw new Error('Provider interrupted');return generateFor(r)(prompt);},produce:async()=>{}}),/interrupted/);
 const partial=requestById(r.id);assert.equal(partial.posts.length,0);
 assert.equal(JSON.parse(one('SELECT plan_json FROM campaigns WHERE id=?',partial.campaign_id).plan_json).items.length,7);
 const resumed=[];
 await runAgent(r.id,()=>{},{generate:async prompt=>{const data=await generateFor(r)(prompt);resumed.push(...data.posts.map(p=>p.day));return data;},produce:async()=>{}});
 assert.equal(requestById(r.id).posts.length,31);assert.equal(resumed.length,24);assert.ok(resumed.every(day=>day>7));
});
